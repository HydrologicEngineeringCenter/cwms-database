CREATE TABLE AT_A2W_ATTRIBUTES
(
  LOCATION_CODE NUMBER NOT NULL,
  DATE_REFRESHED DATE NOT NULL,
  NOTES CLOB,
  DISPLAY_FLAG VARCHAR2(1 BYTE) DEFAULT 'F' NOT NULL,
  LAKE_SUMMARY_TF VARCHAR2(1 BYTE) DEFAULT 'F' NOT NULL,
  OPENING_SOURCE_OBJ VARCHAR2(5 BYTE),
  CONSTRAINT AT_A2W_ATTRIBUTES_PK PRIMARY KEY (LOCATION_CODE) USING INDEX TABLESPACE CWMS_20DATA,
  CONSTRAINT AT_A2W_ATTRIBUTES_FK1 FOREIGN KEY (LOCATION_CODE) REFERENCES AT_PHYSICAL_LOCATION (LOCATION_CODE),
  CONSTRAINT AT_A2W_ATTRIBUTES_CK1 CHECK (DISPLAY_FLAG IN ('T', 'F')),
  CONSTRAINT AT_A2W_ATTRIBUTES_CK2 CHECK (LAKE_SUMMARY_TF IN ('T', 'F')),
  CONSTRAINT AT_A2W_ATTRIBUTES_CK3 CHECK (OPENING_SOURCE_OBJ IN ('OBJ', 'TS'))
) TABLESPACE CWMS_20DATA
LOB (NOTES) STORE AS SYS_LOB_A2W_ATTRIBUTES
(
  ENABLE STORAGE IN ROW
  CHUNK 8192
  RETENTION
  NOCACHE
  LOGGING
  TABLESPACE CWMS_20AT_DATA
);

CREATE INDEX AT_A2W_ATTRIBUTES_I1 ON AT_A2W_ATTRIBUTES (DISPLAY_FLAG ASC, LOCATION_CODE ASC)
TABLESPACE CWMS_20DATA;

COMMENT ON TABLE AT_A2W_ATTRIBUTES IS 'Location presentation metadata for AT_A2W_TS_CODES_BY_LOC';
COMMENT ON COLUMN AT_A2W_ATTRIBUTES.LOCATION_CODE IS 'Foreign key to AT_PHYSICAL_LOCATION';
COMMENT ON COLUMN AT_A2W_ATTRIBUTES.DATE_REFRESHED IS 'The date this record was created/last updated';
COMMENT ON COLUMN AT_A2W_ATTRIBUTES.NOTES IS 'Any notes generated by the initial data load or the WM through CMA';
COMMENT ON COLUMN AT_A2W_ATTRIBUTES.DISPLAY_FLAG IS 'Flag recording the WM choice to display this location in a hierarchy';
COMMENT ON COLUMN AT_A2W_ATTRIBUTES.LAKE_SUMMARY_TF IS 'The flag recording if this location should be in the lake summary report';
COMMENT ON COLUMN AT_A2W_ATTRIBUTES.OPENING_SOURCE_OBJ IS 'Whether the opening value is sourced from an object or a TS Code (OBJ or TS)';
