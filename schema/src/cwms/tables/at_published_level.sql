CREATE TABLE AT_PUBLISHED_LEVEL (
    LOCATION_CODE NUMBER(14) NOT NULL,
    PUBLISHED_ID VARCHAR2(24) NOT NULL,
    LOCATION_LEVEL_CODE NUMBER(14) NOT NULL,
    CONSTRAINT AT_PUBLISHED_LEVEL_PK PRIMARY KEY (LOCATION_CODE, PUBLISHED_ID, LOCATION_LEVEL_CODE) USING INDEX TABLESPACE CWMS_20AT_DATA,
    CONSTRAINT AT_PUBLISHED_LEVEL_FK_LOC FOREIGN KEY (LOCATION_CODE) REFERENCES AT_PHYSICAL_LOCATION (LOCATION_CODE),
    CONSTRAINT AT_PUBLISHED_LEVEL_FK_PUB FOREIGN KEY (PUBLISHED_ID) REFERENCES CWMS_PUBLISHED_ID (PUBLISHED_ID),
    CONSTRAINT AT_PUBLISHED_LEVEL_FK_LEVEL FOREIGN KEY (LOCATION_LEVEL_CODE) REFERENCES AT_LOCATION_LEVEL (LOCATION_LEVEL_CODE)
) TABLESPACE CWMS_20AT_DATA;

COMMENT ON TABLE AT_PUBLISHED_LEVEL IS 'Maps locations and published identifiers to their corresponding published levels';
COMMENT ON COLUMN AT_PUBLISHED_LEVEL.LOCATION_CODE IS 'Foreign key to AT_PHYSICAL_LOCATION';
COMMENT ON COLUMN AT_PUBLISHED_LEVEL.PUBLISHED_ID IS 'Foreign key to CWMS_PUBLISHED_ID';
COMMENT ON COLUMN AT_PUBLISHED_LEVEL.LOCATION_LEVEL_CODE IS 'Foreign key to AT_LOCATION_LEVEL';
